//  ЧТЕНИЕ ИГРЫ ДЛЯ ESP. Отдельный процесс HUD сам ходит в память Standoff 2 и
//  раз в кадр публикует «снимок» — готовый список игроков в нормализованных
//  координатах экрана. Рисовальщик (HUDOverlayView) этот снимок просто читает
//  и красит: он не знает ничего о памяти игры, поэтому тормозов от чтения
//  памяти на главном потоке нет.
//
//  ПРОЕКЦИЯ. Мир→экран считается по4x4 матрице вида/проекции, которую читаем
//  из памяти игры. Результат нормализован (0..1) — пиксельного разрешения
//  игры не требуется, а поворот экрана обрабатывает сама сцена HUD.
//
//  СМЕЩЕНИЯ. Стандофф — IL2CPP-игра, смещения полей меняются с каждым
//  обновлением. Поэтому все смещения читаются из общего plist
//  (ascent.overlay.plist, ключи «esp.off.*»): их можно поправить на устройстве
//  и перезапустить HUD, не пересобирая приложение.
//

#ifndef ASCENT_GAME_ESP_H
#define ASCENT_GAME_ESP_H

#import <Foundation/Foundation.h>
#import <CoreGraphics/CoreGraphics.h>

/// Сколько игроков держим в одном кадре. Фиксированный массив: снимок
/// копируется целиком, без аллокаций в потоке рисования.
#define kAscentESPMaxPlayers 40

/// Один игрок в кадре ESP. Все координаты нормализованы: 0 — левый/верхний
/// край экрана игры, 1 — правый/нижний. Отрицательные значения означают
/// «данных нет».
typedef struct {
    CGPoint screen;      ///< точка ног (или центра, если размера нет)
    float   boxHeight;   ///< высота бокса в долях высоты экрана
    float   health;      ///< 0..100; отрицательно — нет данных
    int     team;        ///< команда; -1 — данных нет
    int     distance;    ///< метры до игрока; отрицательно — данных нет
    char    name[32];    ///< имя, пустая строка — нет данных
} AscentESPPlayer;

/// Описание кадра. frameId растёт при каждом обновлении — рисовальщик видит,
/// что данные свежие, и не мигает старым кадром.
typedef struct {
    int  count;          ///< сколько игроков в массиве
    int  frameId;
    BOOL live;           ///< чтение идёт прямо сейчас (игра видна и процесс жив)
    int  pid;            ///< процесс игры, 0 — не подключены
    BOOL ready;          ///< смещения заданы и первый проход прошёл
    char status[128];    ///< короткая причина «почему пусто» — видна в Misc
} AscentESPFrame;

/// Копия текущего кадра ESP в буфер вызывающего. Возвращает число игроков.
/// Функция потокобезопасна: можно звать из любого потока.
int AscentESPGetFrame(AscentESPPlayer *outPlayers, int capacity, AscentESPFrame *outInfo);

/// Включает/выключает фоновое чтение памяти игры (15 кадров в секунду).
void AscentESPSetEnabled(BOOL enabled);
BOOL AscentESPIsEnabled(void);

/// Читает переключатели из общего файла (cheat.esp) и запускает чтение при
/// необходимости. Вызывается HUD-процессом на старте.
void AscentESPSyncFromState(void);

/// Диагностика: пишет в журнал, что удалось прочитать по текущим смещениям.
/// Нужно, чтобы на устройстве понять, какие смещения правильные.
void AscentESPRunProbe(void);

#endif
