//    • ищет метаданные il2cpp по магии 0xFAB11BAF (global-metadata.dat,
//      обычно замаплен в процесс);
//    • если нашёл — печатает шапку метаданных (версия + смещения таблиц).
//
//  По строкам журнала видно: замаплены ли метаданные, какая у них версия и где
//  лежат таблицы классов/полей — это фундамент для резолвера в Il2Cpp.mm.
